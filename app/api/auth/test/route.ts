import { getSession } from "@/server/auth"
import { NextRequest, NextResponse } from "next/server"

export async function GET(req: NextRequest) {
  const session = await getSession()

  if (!session) {
    return NextResponse.json(
      {
        err: "Unauthorized",
      },
      {
        status: 401,
      }
    )
  }

  return NextResponse.json(
    {
      user: session.user,
    },
    {
      status: 200,
    }
  )
}
